# MAIN — demo on the dummy dataset
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    outlets = pd.read_csv(os.path.join(DATA_DIR, "outlets.csv"))
    demographics = pd.read_csv(os.path.join(DATA_DIR, "demographics_grid.csv"))
    competitors = pd.read_csv(os.path.join(DATA_DIR, "competitor_pois.csv"))
    foot_traffic = pd.read_csv(os.path.join(DATA_DIR, "foot_traffic_transactions.csv"))

    # one example per brand
    sample_outlets = [
        outlets[outlets.brand == "Marugame Udon"].iloc[0],
        outlets[outlets.brand == "The Harvest"].iloc[0],
    ]

    for outlet in sample_outlets:
        profile = build_insight_profile(outlet, demographics, competitors, foot_traffic)
        result = assemble_prompt(profile)

        print("=" * 70)
        print(f"Outlet: {result['outlet_id']} ({result['brand']})")
        print(f"Insight profile: {result['insight_profile']}")
        print(f"\nPrompt:\n{result['prompt']}")
        print(f"\nNegative prompt:\n{result['negative_prompt']}")
        print()
